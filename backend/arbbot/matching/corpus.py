"""Record public metadata explicitly, then evaluate labeled fixtures without network access."""

import argparse
import asyncio
import json
from decimal import Decimal
from pathlib import Path
from urllib.parse import quote

import httpx

from arbbot.domain import utcnow
from arbbot.exchanges.base import ExchangeHTTP
from arbbot.exchanges.kalshi import BASE, KalshiAdapter
from arbbot.exchanges.polymarket import GAMMA, PolymarketAdapter
from arbbot.matching.extraction import extract_contract


def normalize_record(record):
    adapter = KalshiAdapter if record["venue"] == "kalshi" else PolymarketAdapter
    return adapter.normalize_market(record["payload"])


def supported_record(record):
    item = record["payload"]
    if record["venue"] == "polymarket":
        return PolymarketAdapter.supported(item)
    return (
        item.get("market_type") == "binary"
        and Decimal(str(item.get("notional_value_dollars", "1"))) == 1
    )


def evaluate_corpus(records, labels):
    """Gold facts are independently read from rules, not generated by this extractor."""
    results = []
    for record in records:
        market = normalize_record(record)
        label = labels[market.id]
        draft = extract_contract(market)
        proposed = {name: fact.value for name, fact in draft.definition.facts.items()}
        gold = label["facts"]
        incorrect = {name: value for name, value in proposed.items() if gold.get(name) != value}
        results.append(
            {
                "market_id": market.id,
                "supported_by_adapter": supported_record(record),
                "status": draft.status,
                "correct_fields": sorted(
                    name for name, value in proposed.items() if gold.get(name) == value
                ),
                "missing_labeled_fields": sorted(name for name in gold if name not in proposed),
                "incorrect_fields": incorrect,
                "issues": list(draft.issues),
            }
        )
    return {
        "markets": len(results),
        "supported_by_adapter": sum(row["supported_by_adapter"] for row in results),
        "labeled_fields": sum(len(labels[row["market_id"]]["facts"]) for row in results),
        "correct_fields": sum(len(row["correct_fields"]) for row in results),
        "incorrect_fields": sum(len(row["incorrect_fields"]) for row in results),
        "results": results,
    }


async def record_markets(ids):
    records = []
    async with httpx.AsyncClient(timeout=20) as client:
        http = ExchangeHTTP(client)
        for identifier in ids:
            venue, external_id = identifier.split(":", 1)
            if venue not in {"kalshi", "polymarket"} or not external_id:
                raise ValueError("Expected kalshi:TICKER or polymarket:ID")
            base = BASE if venue == "kalshi" else GAMMA
            url = base + "/markets/" + quote(external_id, safe="")
            data = await http.get(url)
            payload = data["market"] if venue == "kalshi" else data
            records.append(
                {
                    "venue": venue,
                    "source_url": url,
                    "captured_at": utcnow().isoformat(),
                    "payload": payload,
                }
            )
    return records


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    record = sub.add_parser("record")
    record.add_argument("ids", nargs="+")
    record.add_argument("--output", type=Path, required=True)
    report = sub.add_parser("report")
    report.add_argument("--records", type=Path, required=True)
    report.add_argument("--labels", type=Path, required=True)
    args = parser.parse_args()
    if args.command == "record":
        if args.output.exists():
            parser.error("Output exists; use a new filename to preserve recorded evidence")
        records = asyncio.run(record_markets(args.ids))
        args.output.parent.mkdir(parents=True, exist_ok=True)
        with args.output.open("x") as output:
            output.write(json.dumps(records, indent=2) + "\n")
    else:
        result = evaluate_corpus(
            json.loads(args.records.read_text()), json.loads(args.labels.read_text())
        )
        print(json.dumps(result, indent=2))
        if result["incorrect_fields"]:
            raise SystemExit(1)


if __name__ == "__main__":
    main()
